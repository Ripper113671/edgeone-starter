/*
  ============================================================================
  文件：src/font.js —— 点阵字体（屏幕上所有字都是怎么画出来的）
  ============================================================================

  【这个文件是干嘛的？】
  它负责在屏幕上画字：分数、层数、"游戏结束"这些文字。
  但它**不用**浏览器直接画字，而是自己把每个字"烤"成一小块点阵图，
  之后再像贴贴纸一样贴到画面上。

  ----------------------------------------------------------------------------
  【先说一个绕不过去的问题：为什么中文这么麻烦？】
  ----------------------------------------------------------------------------

  这个项目最早用的是自己手画的 3×5 像素英文字母（A~Z、0~9），
  一共 36 个字符，每个字符就是一小段字符画，总共不到 1KB。

  这在纯英文游戏里非常完美 —— 但一换成中文就彻底行不通了：

      常用汉字有 3500 个。
      如果每个字都按 12×12 手画点阵，就是 3500 × 144 = 50 万个像素点，
      写出来要好几万行代码。**这条路走不通。**

  所以中文必须换一种思路：**让浏览器先画出来，我们再把它"像素化"**。

  ----------------------------------------------------------------------------
  【核心思路：把矢量字"降维"成点阵字】
  ----------------------------------------------------------------------------

  完整的流程分四步：

    第 1 步  用浏览器自带的 fillText，把字画在一张小到看不见的画布上
    第 2 步  ★ 超采样 ★：画的时候用 2 倍大小（24px）
    第 3 步  ★ 二值化 ★：读回每个像素的透明度，超过阈值的算"实心"，
             否则算"空心"。这样就把"边缘模糊的矢量字"变成了
             "非黑即白的点阵字"
    第 4 步  把这份点阵缓存起来，以后同一个字直接复用

  为什么要"超采样"（第 2 步）？这是整个方案最巧妙的地方：

      假设直接把 12px 的字二值化 —— 有些笔画正好落在两个像素中间，
      一取阈值就整条断掉，字会缺胳膊少腿。

      而先用 24px 画，再把每 2×2 个像素"平均"成一个像素，
      相当于先让浏览器帮我们把笔画"摊匀"，再一刀切下去。
      断笔的概率大大降低，剩下的全是规整的方块。

  这一步在图形学里叫 **Supersampling（超采样抗锯齿）**，
  是真实游戏引擎里标准的多边形抗锯齿做法，只不过我们这里用它来"反向"工作 ——
  不是为了消除锯齿，而是为了**造出**整齐的像素。

  ----------------------------------------------------------------------------
  【为什么不干脆直接用 fillText？反正浏览器画得挺好看】
  ----------------------------------------------------------------------------

  因为风格会崩。这个游戏的所有画面都是硬边像素方块，
  只有文字边缘糊着一圈半透明灰色的话，看起来会非常廉价、格格不入。
  更要命的是：画布本身只有 320×192，之后会被拉伸放大 4 倍，
  那圈"糊边"也会跟着放大成 4 像素宽的灰糊糊 —— 一眼就露馅。

  二值化之后，每个字都是干净的黑白像素，放大后就是整齐的方块，
  和整个游戏的像素风格完全统一。

  ----------------------------------------------------------------------------
  【你会学到什么？】
  ----------------------------------------------------------------------------
  1. 中文和英文在"字体技术"上的根本差异（全角 vs 半角、几千字 vs 几十字）
  2. 超采样 + 二值化：把引擎自带的矢量字体"像素化"的通用手法
  3. 惰性缓存：同一个字、同一种颜色、同一个缩放，只烤一次
  4. 等宽步进的排版方式：为什么像素游戏里"每个字占的格子宽度固定"更好看

  【阅读建议】
  先看 bakeMono（第 1~3 步的实现），再看 bakeGlyph（上色+缩放），
  最后看 draw（排版）。这三层是"总-分-总"的关系。
  ============================================================================
*/

(function (DG) {
  'use strict';

  // ==========================================================================
  // 一、字号与排版参数
  // ==========================================================================

  /**
   * 字形的基准高度（像素）。所有字都在这个高度上烘焙，之后再整数倍放大。
   *
   * ★ 为什么是 12？★
   * 12 是中文点阵字的经典尺寸（早年 DOS 和 Windows 的宋体点阵字库就是 12×12）。
   * 小于 12（比如 10）笔画会粘连成一坨、认不出来；
   * 大于 12（比如 16）在这个 320×192 的小画布上又太占地方，
   * HUD 上下两行就顶到一起了。12 是"能认清"和"放得下"的平衡点。
   */
  const GH = 12;

  /** 汉字的步进宽度（全角，等于高度，所以汉字是正方形的） */
  const CJK_W = 12;

  /**
   * 半角字符（数字、字母、标点）的步进宽度。
   *
   * ★ 为什么要固定宽度，而不是按字符实际宽度来？★
   * 因为这是像素游戏。像素游戏的字讲究"一个一个格子"，
   * 等宽排版会让整行字看起来非常整齐、有节奏感。
   *
   * 如果按实际宽度（"1"比"8"窄、"i"比"W"窄），
   * 一行动来动去，反而显得杂乱 —— 也完全不像像素字体了。
   */
  const ASCII_W = 7;

  /**
   * 字与字之间的空隙（像素）。
   * ★ 为什么需要它？★
   * 两个字紧挨着会连成一坨。留 1 像素的空隙，眼睛才能把"字"切开。
   */
  const TRACKING = 1;

  /**
   * ★ 超采样倍数 ★（本文件最重要的一个数字，原理见文件头）
   * 2 表示"先用 2 倍大小画，再把每 2×2 个像素合并成 1 个"。
   * 开到 3 或 4 效果会更好一点点，但烘焙耗时按平方增长，不划算。
   */
  const SS = 2;

  /**
   * 二值化的阈值（0~255）。
   *
   * 超采样合并后的灰度值 >= 这个数，就判定为"实心像素"。
   *
   * ★ 调这个数字的体感 ★
   *   调高（比如 180）→ 笔画变细，容易断笔、缺胳膊少腿
   *   调低（比如 60） → 笔画变粗，相邻笔画会粘连成一坨黑
   * 100 左右是反复试出来的甜点：笔画完整，又不会糊成一片。
   */
  const THRESHOLD = 100;

  /**
   * 字体栈。
   *
   * 浏览器会**从左往右**找，用第一个装了的字体。
   * 这里从苹方（macOS/iOS）到微软雅黑（Windows）再到思源黑体（Linux/安卓），
   * 覆盖了绝大多数设备。
   *
   * ★ 必须带最后的 sans-serif ★
   * 万一用户一个都没装，浏览器会退回到自己的默认无衬线字体。
   * 不写这个兜底，某些系统上会直接退化成衬线体（宋体），风格就崩了。
   */
  const FONT_STACK =
    '"PingFang SC","Hiragino Sans GB","Microsoft YaHei","Noto Sans CJK SC",' +
    '"Source Han Sans SC","WenQuanYi Micro Hei",sans-serif';

  // ==========================================================================
  // 二、判断"全角还是半角"
  // ==========================================================================

  /**
   * 判断一个字符该占"全角格"还是"半角格"。
   *
   * 规则很简单：ASCII 范围（码点 < 0x2E80）的都算半角，
   * 其余（汉字、假名、全角标点……）一律按全角处理。
   *
   * ★ 0x2E80 这个数是怎么来的？★
   * 它是 Unicode 里"CJK 部首补充"的起点。
   * 在这之前是拉丁字母、希腊字母、西里尔字母等"窄字符"，
   * 在这之后基本就是方块字的世界了。
   *
   * @param {string} ch 单个字符
   * @returns {boolean} true = 全角（汉字），false = 半角（数字/字母）
   */
  function isWide(ch) {
    return ch.charCodeAt(0) >= 0x2e80;
  }

  // ==========================================================================
  // 三、烘焙第 1 层：把字变成"黑白点阵"
  // ==========================================================================

  /**
   * 缓存：字符 → 点阵数据（一个只含 0/1 的数组）。
   *
   * ★ 注意这一层缓存**不带颜色、不带缩放** ★
   * 因为"这个字长什么形状"和"它是什么颜色、放多大"是完全无关的两件事。
   * 把形状单独缓存下来，那么"白色的分数"和"金色的分数"就能共用同一份形状数据，
   * 省掉最贵的 fillText + getImageData 那一步。
   *
   * 这种"按最本质的维度缓存"的思路，在优化里非常常用。
   */
  const monoCache = {};

  /**
   * ★ 本文件最核心的函数 ★ 把一个字符烤成黑白点阵。
   *
   * 返回的是一个长度为 gw × GH 的一维数组，每个元素是 0（空）或 1（实心）。
   * 用一维数组而不是二维，是因为后面循环时下标计算更简单，
   * 而且能直接用 Uint8Array（每个元素只占 1 字节）。
   *
   * @param {string} ch 单个字符
   * @param {number} gw 这个字符占的格子宽度（汉字 12，半角 7）
   * @returns {Uint8Array} 点阵数据
   */
  function bakeMono(ch, gw) {
    const key = ch + '|' + gw;
    if (monoCache[key]) return monoCache[key];

    // ---- 第 1 步：在放大 SS 倍的画布上，用系统字体把字画出来 ----
    const bw = gw * SS;   // 烘焙画布宽
    const bh = GH * SS;   // 烘焙画布高

    const c = DG.Sprites.makeCanvas(bw, bh);
    const g = c.getContext('2d');

    g.font = 'bold ' + (GH * SS) + 'px ' + FONT_STACK;
    // textAlign / textBaseline 决定 (x, y) 指的是字的哪个部位。
    // 用 center + middle 表示"把字的正中心放在 (x, y)"，最符合直觉。
    g.textAlign = 'center';
    g.textBaseline = 'middle';
    g.fillStyle = '#ffffff';
    // 坐标取整，避免浏览器做亚像素定位导致点阵位置飘忽
    g.fillText(ch, Math.round(bw / 2), Math.round(bh / 2));

    // ---- 第 2 步：读回像素数据 ----
    // getImageData 返回的是一长串 RGBA 数字，每 4 个一组（红、绿、蓝、透明度）。
    // 我们只关心透明度（第 4 个），因为字画在透明背景上，
    // "有字"的地方透明通道才大于 0。
    const src = g.getImageData(0, 0, bw, bh).data;

    // ---- 第 3 步：超采样 + 二值化 ----
    const bits = new Uint8Array(gw * GH);

    for (let y = 0; y < GH; y++) {
      for (let x = 0; x < gw; x++) {
        // 把这个目标像素对应的 SS×SS 个小像素加起来求平均
        let sum = 0;
        for (let sy = 0; sy < SS; sy++) {
          for (let sx = 0; sx < SS; sx++) {
            const px = x * SS + sx;
            const py = y * SS + sy;
            sum += src[(py * bw + px) * 4 + 3]; // +3 就是透明度通道
          }
        }

        // 平均值过阈值就是"实心"，否则是"空心"
        bits[y * gw + x] = (sum / (SS * SS)) >= THRESHOLD ? 1 : 0;
      }
    }

    monoCache[key] = bits;
    return bits;
  }

  // ==========================================================================
  // 四、烘焙第 2 层：给点阵上色、缩放
  // ==========================================================================

  /** 缓存：字符|颜色|缩放 → 烘好的小画布 */
  const glyphCache = {};

  /**
   * 把点阵"涂上颜色"并放大，做成一张可以直接 drawImage 的小画布。
   *
   * ★ 为什么要真的做成一张画布，而不是每帧现场 fillRect？★
   * 假设一行"分数 00123"有 8 个字符，每个字符平均 60 个实心像素。
   * 每帧现场画就是 480 次 fillRect，60 帧就是每秒 2.8 万次调用 —— 纯属浪费。
   *
   * 烤成画布之后，每帧只要 8 次 drawImage。这就是"预计算换性能"，
   * 和 sprites.js 里烘焙精灵是同一个思路。
   *
   * @param {string} ch 单个字符
   * @param {string} color CSS 颜色
   * @param {number} s 整数缩放倍数
   */
  function bakeGlyph(ch, color, s) {
    const key = ch + '|' + color + '|' + s;
    if (glyphCache[key]) return glyphCache[key];

    const gw = isWide(ch) ? CJK_W : ASCII_W;
    const bits = bakeMono(ch, gw);

    const c = DG.Sprites.makeCanvas(gw * s, GH * s);
    const g = c.getContext('2d');
    g.imageSmoothingEnabled = false;
    g.fillStyle = color;

    for (let y = 0; y < GH; y++) {
      for (let x = 0; x < gw; x++) {
        // 一个点阵像素 → 放大成 s×s 的一个方块
        if (bits[y * gw + x]) {
          g.fillRect(x * s, y * s, s, s);
        }
      }
    }

    const spr = { canvas: c, w: gw * s, h: GH * s };
    glyphCache[key] = spr;
    return spr;
  }

  // ==========================================================================
  // 五、绘制接口
  // ==========================================================================

  /**
   * 在指定位置画一行字（左上角对齐）。
   *
   * ★ 中文和英文混排是怎么对齐的？★
   * 它们的高度完全一样（都是 GH = 12），只是占的宽度不同（12 或 7）。
   * 所以只要沿着同一条 y 基准线画下去，中文和数字天然就是对齐的，
   * 不需要任何额外的对齐计算 —— 这就是"统一行高"的好处。
   *
   * @param {CanvasRenderingContext2D} ctx
   * @param {string}  text  要画的文字（中英文、数字都可以）
   * @param {number}  x     左上角 x
   * @param {number}  y     左上角 y
   * @param {string}  color 颜色
   * @param {number}  scale 放大倍数（1 = 原始大小，2 = 两倍，必须是整数）
   * @returns {number} 这行字画完之后的宽度（方便接着画下一段，或做居中）
   */
  function draw(ctx, text, x, y, color, scale) {
    const s = Math.max(1, Math.floor(scale || 1));

    let cursorX = Math.round(x);
    const py = Math.round(y);

    for (let i = 0; i < text.length; i++) {
      const ch = text[i];
      const step = isWide(ch) ? CJK_W : ASCII_W;

      // 空格没有形状，不需要烘焙，只管往前走一格
      if (ch !== ' ') {
        const glyph = bakeGlyph(ch, color, s);
        ctx.drawImage(glyph.canvas, cursorX, py);
      }

      cursorX += (step + TRACKING) * s;
    }

    return cursorX - Math.round(x);
  }

  /**
   * 量一下这行字有多宽（不实际绘制）。
   * 用来做居中、右对齐，或者给文字画背景框。
   */
  function measure(text, scale) {
    const s = Math.max(1, Math.floor(scale || 1));
    if (text.length === 0) return 0;

    let units = 0;
    for (let i = 0; i < text.length; i++) {
      units += (isWide(text[i]) ? CJK_W : ASCII_W) + TRACKING;
    }

    // 最后一个字符后面不用留间距，所以最后要减掉一个
    return units * s - TRACKING * s;
  }

  /** 字体的行高（画多行文字时用来算下一行的 y） */
  function lineHeight(scale) {
    return GH * Math.max(1, Math.floor(scale || 1));
  }

  /**
   * 画一行居中于某个 x 坐标的文字。
   * 这是最常用的排版方式（标题、提示语基本都要居中）。
   *
   * @param {number} centerX 想让文字的中心对齐到这个 x
   */
  function drawCentered(ctx, text, centerX, y, color, scale) {
    const w = measure(text, scale);
    return draw(ctx, text, centerX - w / 2, y, color, scale);
  }

  /**
   * ★ 预热 ★ 提前把一批字烤好。
   *
   * 为什么需要它？因为烘焙一个字要跑 fillText + getImageData，
   * 而 getImageData 是出了名的慢（它要把 GPU 上的画面读回内存）。
   *
   * 如果全留着"用到才烤"，游戏第一次显示"游戏结束"四个字时，
   * 会有一个肉眼可见的卡顿 —— 因为那一帧要连续烤 4 个新字。
   * 提前在启动时烤好，游戏过程就始终丝滑。
   *
   * @param {string[]} texts 预期会用到的所有文案
   */
  function warmUp(texts) {
    for (let i = 0; i < texts.length; i++) {
      const t = texts[i];
      for (let j = 0; j < t.length; j++) {
        const ch = t[j];
        if (ch === ' ') continue;
        bakeMono(ch, isWide(ch) ? CJK_W : ASCII_W);
      }
    }
  }

  // ==========================================================================
  // 六、导出
  // ==========================================================================

  DG.Font = {
    draw: draw,
    measure: measure,
    lineHeight: lineHeight,
    drawCentered: drawCentered,
    warmUp: warmUp,

    /** 字形尺寸，供需要精细排版的代码使用 */
    GLYPH_W: ASCII_W,
    GLYPH_H: GH,
    CJK_W: CJK_W,
    ASCII_W: ASCII_W,
  };

})(window.DG);
