  // ==========================================================================
  // 七、小工具函数（数学 / 随机）
  // ==========================================================================

  /** 把数字限制在 [lo, hi] 区间内。比如 clamp(-5, 0, 10) 得到 0，clamp(99, 0, 10) 得到 10 */
  DG.clamp = function (v, lo, hi) {
    return v < lo ? lo : v > hi ? hi : v;
  };

  /** 取两个数里更大的那个 */
  DG.max = function (a, b) {
    return a > b ? a : b;
  };

  /** 取两个数里更小的那个 */
  DG.min = function (a, b) {
    return a < b ? a : b;
  };

  /**
   * 线性插值（Linear Interpolation，游戏开发里常简称 lerp）。
   *
   * 作用：在 a 和 b 之间，按比例 t 取一个中间值。
   *   lerp(0, 100, 0)   → 0    （t=0 时取起点）
   *   lerp(0, 100, 0.5) → 50   （t=0.5 时取中点）
   *   lerp(0, 100, 1)   → 100  （t=1 时取终点）
   *
   * 游戏里到处都在用它做"平滑跟随"：相机、血条动画、颜色过渡……
   * 它比"直接瞬间跳到目标值"看起来自然得多。
   */
  DG.lerp = function (a, b, t) {
    return a + (b - a) * t;
  };

  /**
   * 取 [lo, hi) 区间内的随机整数。
   * Math.random() 返回 [0, 1) 的小数，乘上范围再加偏移就是我们要的区间。
   * 注意 Math.floor 是向下取整，所以 hi 本身取不到 —— 这正好方便处理数组索引。
   */
  DG.randInt = function (lo, hi) {
    return Math.floor(Math.random() * (hi - lo)) + lo;
  };

  /** 取 [lo, hi) 区间内的随机小数（带小数点的那种） */
  DG.randFloat = function (lo, hi) {
    return Math.random() * (hi - lo) + lo;
  };

  /** 从数组里随机挑一个元素 */
  DG.pick = function (arr) {
    return arr[Math.floor(Math.random() * arr.length)];
  };

  /**
   * 生成一个"伪随机"函数。
   *
   * ★ 这解决了一个很有意思的问题：地面纹理要看起来随机，但不能每帧都变 ★
   *
   * 如果直接用 Math.random() 画地面噪点，那么每一帧的噪点位置都不一样，
   * 画面会疯狂闪烁，像电视机雪花。
   *
   * 解决办法：用坐标当"种子"算出一个固定的伪随机值。
   * 同一个坐标永远算出同一个值，所以噪点就"钉"在地上了。
   *
   * 这里用的是经典的一维整数哈希算法（把数字打乱但结果稳定），
   * 类似的做法在真正的游戏引擎里到处都是。
   */
  DG.hash2d = function (x, y) {
    // 先用大质数把 x、y 搅拌开，让相邻坐标的结果差异巨大
    let h = x * 374761393 + y * 668265263;
    // 位运算把结果限制在 32 位整数范围内，避免超出精度
    h = (h ^ (h >> 13)) * 1274126177;
    h = h ^ (h >> 16);
    // 转成 0~1 之间的小数（>>> 0 是"转成无符号 32 位整数"，防止出现负数）
    return (h >>> 0) / 4294967296;
  };

